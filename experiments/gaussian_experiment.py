"""Reproduce synthetic noise/detail comparisons with stdlib and pinned Pillow."""

import argparse
import csv
import hashlib
import io
import json
import math
import platform
import random
import statistics
import sys
from pathlib import Path

from PIL import Image, ImageDraw, __version__ as pillow_version

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from image_processing import (  # noqa: E402
    GAUSSIAN_ALGORITHM_ID, GAUSSIAN_ALGORITHM_VERSION, gaussian_blur,
)

RADII = (0, 1, 2, 4)
NOISE_LEVELS = (0, 5, 20, 40)
SEED = 20261115


def png_bytes(image):
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


def clean_image():
    path = Path(__file__).resolve().with_name("Lenna.png")
    with Image.open(path) as image:
        return image.convert("RGB").resize((256, 256), Image.Resampling.LANCZOS)


def noisy_image(clean, sigma):
    rng = random.Random(SEED)  # same noise realization scaled across conditions
    pixels = []
    for value in clean.convert("L").tobytes():
        noisy = max(0, min(255, round(value + rng.gauss(0, sigma))))
        pixels.append((noisy, noisy, noisy))
    result = Image.new("RGB", clean.size)
    result.putdata(pixels)
    return result


def metrics(result, clean):
    gray = result.convert("L")
    errors = [a-b for a, b in zip(gray.tobytes(), clean.convert("L").tobytes())]
    mse = statistics.mean(e*e for e in errors)
    edge = statistics.mean(gray.getpixel((128, y))-gray.getpixel((127, y)) for y in range(64, 192))
    line = statistics.mean((gray.getpixel((60, y))+gray.getpixel((61, y)))/2-gray.getpixel((52, y)) for y in range(64, 192))
    return {"rmse": math.sqrt(mse),
            "flat_variance": statistics.pvariance(gray.crop((16, 64, 48, 192)).tobytes()),
            "step_contrast": edge, "thin_line_contrast": line}


def run(output):
    output.mkdir(parents=True, exist_ok=True)
    clean = clean_image()
    clean.save(output / "clean.png")
    sheet = Image.new("RGB", (6*256, 4*286), "#18202b")
    draw = ImageDraw.Draw(sheet)
    rows, sources = [], []
    for row_index, noise in enumerate(NOISE_LEVELS):
        source = noisy_image(clean, noise)
        raw = png_bytes(source)
        source_id = hashlib.sha256(raw).hexdigest()
        (output / f"noise-{noise}.png").write_bytes(raw)
        sources.append({"noise_sigma": noise, "source_id": source_id})
        images = [("Reference", clean), (f"Input noise={noise}", source)]
        before = source.tobytes()
        for radius in RADII:
            result = gaussian_blur(source, radius)
            assert source.tobytes() == before, "source was modified"
            filename = f"noise-{noise}-radius-{radius}.png"
            result.save(output / filename)
            rows.append({"noise_sigma": noise, "radius_px": radius,
                         **{key: round(value, 6) for key, value in metrics(result, clean).items()},
                         "source_id": source_id, "result_file": filename})
            images.append((f"Radius={radius}px", result))
        for col, (label, image) in enumerate(images):
            x, y = col*256, row_index*286
            draw.text((x+8, y+8), label, fill="white")
            sheet.paste(image, (x, y+30))
    sheet.save(output / "comparison.png")
    with (output / "metrics.csv").open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    manifest = {"algorithm_id": GAUSSIAN_ALGORITHM_ID,
                "algorithm_version": GAUSSIAN_ALGORITHM_VERSION,
                "python": platform.python_version(), "pillow": pillow_version,
                "seed": SEED, "noise_sigma": NOISE_LEVELS, "radius_px": RADII,
                "size": clean.size, "mode": clean.mode,
                "flat_roi_ltrb_exclusive": [16, 64, 48, 192],
                "sources": sources,
                "output_sha256": {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
                                  for path in sorted(output.glob("*.png"))}}
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2)+"\n", encoding="utf-8")
    table = ["# Gaussian comparison: measured results", "",
             "Generated by `experiments/gaussian_experiment.py`. Values use 8-bit L intensity.", "",
             "| Noise sigma | Radius px | RMSE vs clean | Flat variance | Step contrast | Thin-line contrast |",
             "|---:|---:|---:|---:|---:|---:|"]
    for row in rows:
        table.append("| {noise_sigma} | {radius_px} | {rmse:.3f} | {flat_variance:.3f} | {step_contrast:.3f} | {thin_line_contrast:.3f} |".format(**row))
    (output / "summary.md").write_text("\n".join(table)+"\n", encoding="utf-8")
    print("\n".join(table))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "docs/image-processing/results/gaussian")
    run(parser.parse_args().output)
